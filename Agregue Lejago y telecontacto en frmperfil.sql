IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'Usuarios' AND COLUMN_NAME = 'legajo')
BEGIN
    ALTER TABLE Usuarios ADD legajo VARCHAR(50) NULL;
END

IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'Usuarios' AND COLUMN_NAME = 'telefono')
BEGIN
    ALTER TABLE Usuarios ADD telefono VARCHAR(50) NULL;
END